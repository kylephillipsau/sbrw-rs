#!/usr/bin/env python3
"""Generate Rust sources and assets from upstream and from JVM recordings.

  tools/gen.py tlds          crates/sbrw-java/src/validator/tlds.rs from fixtures/vectors/email_validator.json
  tools/gen.py schema        assets/static.sql and crates/sbrw-core/migrations/0001_upstream_schema.sql
                             from upstream Schema.sql and Data.sql
  tools/gen.py engine-codes  crates/sbrw-core/src/engine/codes.rs from upstream EngineExceptionCode.java
  tools/gen.py routes        crates/sbrw-http/src/engine/routes.rs from port/inventory.json
  tools/gen.py all           everything

Generated files are committed and start with a "generated by" line; edit the
inputs or this script, never the outputs.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def header(source: str) -> str:
    return f"// Generated by tools/gen.py from {source}. Do not edit.\n\n"


def tlds() -> None:
    vectors = json.loads((ROOT / "fixtures/vectors/email_validator.json").read_text())
    out = [header("fixtures/vectors/email_validator.json (commons-validator 1.7 DomainValidator)")]
    for name, entries in vectors["tlds"].items():
        const = name.removesuffix("_RO") + "_TLDS"
        # DomainValidator keeps its arrays sorted for binary search; so do we.
        assert entries == sorted(entries), f"{name} is not sorted"
        if name == "LOCAL_RO":
            out.append("// Only DomainValidator.getInstance(allowLocal = true) consults these.\n#[allow(dead_code)]\n")
        out.append(f"pub(super) static {const}: [&str; {len(entries)}] = [\n")
        out += [f"    {json.dumps(e)},\n" for e in entries]
        out.append("];\n\n")
    path = ROOT / "crates/sbrw-java/src/validator/tlds.rs"
    path.write_text("".join(out).rstrip() + "\n")
    print(f"wrote {path.relative_to(ROOT)}")


MYSQL = ROOT / "upstream/setting-up-sbrw/Files/MySQL scripts"


def parse_schema(text: str) -> list[dict]:
    """The CREATE TABLE statements of upstream's Schema.sql, in order."""
    tables = []
    for m in re.finditer(r"CREATE TABLE `(\w+)`\s*\((.*?)\n\)\s*ENGINE(.*?);", text, re.S):
        name, body, options = m.groups()
        table = {"name": name, "columns": [], "pk": [], "unique": [], "keys": [], "fks": []}
        ai = re.search(r"AUTO_INCREMENT\s*=\s*(\d+)", options)
        table["auto_increment_start"] = int(ai.group(1)) if ai else None
        for line in (l.strip().rstrip(",") for l in body.splitlines()):
            if not line:
                continue
            if line.startswith("`"):
                col = re.match(r"`(\w+)`\s+(\w+)(?:\(([^)]*)\))?\s*(.*)", line)
                cname, ctype, cargs, rest = col.groups()
                table["columns"].append(
                    {
                        "name": cname,
                        "type": ctype.lower(),
                        "args": cargs,
                        "not_null": "NOT NULL" in rest,
                        "auto_increment": "AUTO_INCREMENT" in rest,
                        "default": parse_default(rest),
                    }
                )
            elif line.startswith("PRIMARY KEY"):
                table["pk"] = cols(line)
            elif line.startswith("UNIQUE KEY"):
                table["unique"].append((re.search(r"KEY `(\w+)`", line).group(1), cols(line)))
            elif line.startswith("KEY"):
                table["keys"].append((re.search(r"KEY `(\w+)`", line).group(1), cols(line)))
            elif line.startswith("CONSTRAINT"):
                fk = re.match(r"CONSTRAINT `\w+` FOREIGN KEY \(`(\w+)`\) REFERENCES `(\w+)` \(`(\w+)`\)(.*)", line)
                table["fks"].append(
                    {"column": fk.group(1), "table": fk.group(2), "ref": fk.group(3), "cascade": "CASCADE" in fk.group(4)}
                )
            else:
                raise ValueError(f"{name}: unrecognised line {line!r}")
        tables.append(table)
    return tables


def cols(line: str) -> list[str]:
    inner = line[line.index("(") + 1 : line.rindex(")")]
    return [c.strip() for c in inner.split(",")]


def parse_default(rest: str):
    m = re.search(r"DEFAULT (b'[01]'|'[^']*'|NULL|CURRENT_TIMESTAMP|[-\d.]+)", rest)
    return m.group(1) if m else None


def sqlite_type(col: dict) -> str:
    t = col["type"]
    if t == "bit" or (t == "tinyint" and col["args"] == "1"):
        # Connector/J reads both as Boolean; snapshots dump these as JSON booleans.
        return "BOOLEAN"
    if t in ("bigint", "int", "smallint", "tinyint", "mediumint"):
        return "INTEGER"
    if t in ("double", "float", "decimal"):
        return "REAL"
    if t in ("varchar", "char", "text", "longtext", "mediumtext", "tinytext", "enum"):
        # utf8mb4_unicode_ci compares case-insensitively; SQLite's NOCASE covers ASCII.
        return "TEXT COLLATE NOCASE"
    if t in ("datetime", "timestamp", "date"):
        # MySQL's text format, so snapshots match: 'YYYY-MM-DD hh:mm:ss'.
        return "TEXT"
    if t in ("blob", "longblob", "mediumblob"):
        return "BLOB"
    raise ValueError(f"unmapped MySQL type {t}")


def sqlite_default(col: dict) -> str:
    d = col["default"]
    if d is None or d == "NULL":
        return ""
    if d == "CURRENT_TIMESTAMP":
        # MySQL fills this from its clock; sbrw-rs always supplies the value from Env.
        return ""
    if d.startswith("b'"):
        return f" DEFAULT {d[2]}"
    if d.startswith("'") and sqlite_type(col) in ("INTEGER", "REAL", "BOOLEAN"):
        return f" DEFAULT {d[1:-1]}"
    return f" DEFAULT {d}"


def create_table(table: dict, schema: str, keep_fks: set[str]) -> str:
    lines = []
    single_ai = len(table["pk"]) == 1 and any(c["auto_increment"] for c in table["columns"])
    for c in table["columns"]:
        decl = f'"{c["name"]}" {sqlite_type(c)}'
        if single_ai and c["name"] == table["pk"][0].strip("`"):
            decl = f'"{c["name"]}" INTEGER PRIMARY KEY AUTOINCREMENT'
        else:
            if c["not_null"]:
                decl += " NOT NULL"
            decl += sqlite_default(c)
        lines.append(decl)
    if table["pk"] and not single_ai:
        lines.append("PRIMARY KEY (" + ", ".join(p.strip("`").join('""') for p in table["pk"]) + ")")
    for fk in table["fks"]:
        if fk["table"] in keep_fks:
            clause = f'FOREIGN KEY ("{fk["column"]}") REFERENCES "{fk["table"]}" ("{fk["ref"]}")'
            lines.append(clause + (" ON DELETE CASCADE" if fk["cascade"] else ""))
    sql = f'CREATE TABLE {schema}"{table["name"]}" (\n    ' + ",\n    ".join(lines) + "\n);\n"
    for unique, (kname, kcols) in [(True, k) for k in table["unique"]] + [(False, k) for k in table["keys"]]:
        if not unique and len(kcols) == 1 and any(f["column"] == kcols[0].strip("`") for f in table["fks"]):
            pass  # MySQL's implicit FK index; keep it, it helps cascades too
        columns = ", ".join(re.sub(r"`(\w+)`", r'"\1"', k) for k in kcols)
        kind = "UNIQUE INDEX" if unique else "INDEX"
        sql += f'CREATE {kind} {schema}"{table["name"]}__{kname}" ON "{table["name"]}" ({columns});\n'
    return sql


def mysql_values(text: str, start: int) -> tuple[list[list], int]:
    """Parse `(v, ...), (...);` from text[start:]; returns rows and the index after ';'."""
    rows, i, n = [], start, len(text)
    escapes = {"0": "\0", "'": "'", '"': '"', "b": "\b", "n": "\n", "r": "\r", "t": "\t", "Z": "\x1a", "\\": "\\"}
    while True:
        while text[i] in " \n,":
            i += 1
        if text[i] == ";":
            return rows, i + 1
        assert text[i] == "(", text[i : i + 40]
        i += 1
        row = []
        while True:
            while text[i] == " ":
                i += 1
            if text.startswith("_binary '", i):
                i += len("_binary '")
                raw = ""
                while text[i] != "'":
                    if text[i] == "\\":
                        raw += escapes.get(text[i + 1], "\\" + text[i + 1])
                        i += 2
                    else:
                        raw += text[i]
                        i += 1
                i += 1
                assert raw in ("\0", "\x01"), repr(raw)
                row.append(raw == "\x01")
            elif text[i] == "'":
                i += 1
                s = []
                while text[i] != "'" or text[i + 1] == "'":
                    if text[i] == "'":
                        s.append("'")
                        i += 2
                    elif text[i] == "\\":
                        s.append(escapes.get(text[i + 1], "\\" + text[i + 1]))
                        i += 2
                    else:
                        s.append(text[i])
                        i += 1
                i += 1
                row.append("".join(s))
            elif text.startswith("NULL", i):
                row.append(None)
                i += 4
            else:
                m = re.compile(r"-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?").match(text, i)
                row.append(m.group(0))
                i = m.end()
            while text[i] == " ":
                i += 1
            if text[i] == ",":
                i += 1
                continue
            assert text[i] == ")", text[i : i + 40]
            i += 1
            break
        rows.append(row)
        if i >= n:
            raise ValueError("unterminated INSERT")


def sqlite_literal(v) -> str:
    if v is None:
        return "NULL"
    if v is True or v is False:
        return "1" if v else "0"
    if isinstance(v, str) and not re.fullmatch(r"-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?", v):
        return "'" + v.replace("'", "''") + "'"
    if isinstance(v, str) and v.startswith("'"):
        return v
    return v


def schema() -> None:
    """assets/static.sql and the runtime schema from upstream's Schema.sql and Data.sql."""
    tables = parse_schema((MYSQL / "2. Schema.sql").read_text(encoding="utf-8"))
    data = (MYSQL / "3. Data.sql").read_text(encoding="utf-8")
    inserts: dict[str, list[list]] = {}
    for m in re.finditer(r"INSERT INTO `(\w+)` VALUES ", data):
        rows, _ = mysql_values(data, m.end())
        inserts.setdefault(m.group(1), []).extend(rows)

    static = [t for t in tables if t["name"] in inserts]
    runtime = [t for t in tables if t["name"] not in inserts]
    runtime_names = {t["name"] for t in runtime}

    out = [header("upstream Schema.sql and Data.sql (setting-up-sbrw@2089af6)").replace("//", "--")]
    out.append("-- Static game data, loaded into the attached `static` schema. Read-only at runtime\n")
    out.append("-- except `parameter`, which config overrides are written into at startup.\n\n")
    for t in static:
        out.append(create_table(t, "", set()))
        cols_by_name = {c["name"]: c for c in t["columns"]}
        for row in inserts[t["name"]]:
            assert len(row) == len(t["columns"]), (t["name"], len(row), len(t["columns"]))
        names = [c["name"] for c in t["columns"]]
        rows = inserts[t["name"]]
        for chunk in range(0, len(rows), 500):
            values = ",\n".join(
                "(" + ",".join(literal_for(cols_by_name[n], v) for n, v in zip(names, row)) + ")"
                for row in rows[chunk : chunk + 500]
            )
            out.append(f'INSERT INTO "{t["name"]}" VALUES\n{values};\n')
        out.append("\n")
    (ROOT / "assets").mkdir(exist_ok=True)
    (ROOT / "assets/static.sql").write_text("".join(out))

    ddl = [header("upstream Schema.sql (setting-up-sbrw@2089af6)").replace("//", "--")]
    ddl.append("-- Runtime tables: same names, columns and column order as upstream's MySQL schema.\n")
    ddl.append("-- Foreign keys into static tables are left out (SQLite can't reference another schema).\n\n")
    seeds = []
    for t in runtime:
        ddl.append(create_table(t, "", runtime_names))
        ddl.append("\n")
        if t["auto_increment_start"] and t["auto_increment_start"] > 1:
            seeds.append(f"INSERT INTO sqlite_sequence (name, seq) VALUES ('{t['name']}', {t['auto_increment_start'] - 1});\n")
    ddl.append("-- AUTO_INCREMENT starting values from the MySQL table options.\n")
    ddl += seeds
    path = ROOT / "crates/sbrw-core/migrations/0001_upstream_schema.sql"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(ddl))
    counts = {t["name"]: len(inserts[t["name"]]) for t in static}
    print(f"wrote assets/static.sql ({len(static)} tables: {counts})")
    print(f"wrote {path.relative_to(ROOT)} ({len(runtime)} runtime tables)")


def literal_for(col: dict, v) -> str:
    if v is True or v is False or v is None:
        return sqlite_literal(v)
    if sqlite_type(col) in ("INTEGER", "REAL", "BOOLEAN") and re.fullmatch(r"-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?", v):
        return v
    return "'" + v.replace("'", "''") + "'"


def engine_codes() -> None:
    """EngineExceptionCode from upstream's enum."""
    src = (ROOT / "upstream/soapbox-race-core/src/main/java/com/soapboxrace/core/engine/EngineExceptionCode.java").read_text()
    codes = re.findall(r"^\s+(\w+)\((-?\d+)\)[,;]", src, re.M)
    assert len(codes) == 192, len(codes)
    out = [header("upstream engine/EngineExceptionCode.java")]
    out.append("/// Error codes the game client understands, as upstream's `EngineExceptionCode`.\n")
    out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub enum EngineExceptionCode {\n")
    out += [f"    {name},\n" for name, _ in codes]
    out.append("}\n\nimpl EngineExceptionCode {\n    pub fn error_code(self) -> i32 {\n        match self {\n")
    out += [f"            Self::{name} => {code},\n" for name, code in codes]
    out.append("        }\n    }\n}\n")
    path = ROOT / "crates/sbrw-core/src/engine/codes.rs"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(out))
    print(f"wrote {path.relative_to(ROOT)} ({len(codes)} codes)")


def routes() -> None:
    """The JAX-RS route table under /Engine.svc, from port/inventory.json."""
    inv = json.loads((ROOT / "port/inventory.json").read_text())
    rows = []
    for c in inv["classes"]:
        if c["kind"] != "api" or "path" not in c:
            continue
        class_path = "/" + c["path"].strip("/")
        for u in c["units"]:
            if "http" not in u:
                continue
            verb, _, sub = u["http"].partition(" ")
            full = class_path.rstrip("/") + ("/" + sub.strip("/") if sub.strip("/") else "")
            rows.append(
                (
                    verb,
                    class_path,
                    full or "/",
                    "Secured" in u["annotations"],
                    "LauncherChecks" in u["annotations"],
                    u.get("produces"),
                    u["id"],
                )
            )
    out = [header("port/inventory.json")]
    out.append("use super::Route;\n\n")
    out.append("/// Every upstream JAX-RS resource method under `/Engine.svc`.\n")
    out.append(f"pub const ROUTES: [Route; {len(rows)}] = [\n")
    for verb, cls, full, secured, launcher, produces, unit in rows:
        prod = f"Some({json.dumps(produces)})" if produces else "None"
        out.append(
            f"    Route {{ method: {json.dumps(verb)}, class: {json.dumps(cls)}, path: {json.dumps(full)}, "
            f"secured: {str(secured).lower()}, launcher_checks: {str(launcher).lower()}, produces: {prod}, "
            f"unit: {json.dumps(unit)} }},\n"
        )
    out.append("];\n")
    path = ROOT / "crates/sbrw-http/src/engine/routes.rs"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(out))
    print(f"wrote {path.relative_to(ROOT)} ({len(rows)} routes)")


TARGETS = {"tlds": tlds, "schema": schema, "engine-codes": engine_codes, "routes": routes}

if __name__ == "__main__":
    target = sys.argv[1] if len(sys.argv) > 1 else ""
    if target == "all":
        for fn in TARGETS.values():
            fn()
    elif target in TARGETS:
        TARGETS[target]()
    else:
        sys.exit(__doc__)
