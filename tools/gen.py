def routes() -> None:
    """The JAX-RS route table under /Engine.svc, from port/inventory.json."""
    inv = json.loads((ROOT / "port/inventory.json").read_text())
    rows = []
    for c in inv["classes"]:
        if c["kind"] != "api" or "path" not in c:
            continue
        class_path = "/" + c["path"].strip("/")
        for u in c["units"]:
            if "http" not in u:
                continue
            verb, _, sub = u["http"].partition(" ")
            full = class_path.rstrip("/") + ("/" + sub.strip("/") if sub.strip("/") else "")
            rows.append(
                (
                    verb,
                    class_path,
                    full or "/",
                    "Secured" in u["annotations"],
                    "LauncherChecks" in u["annotations"],
                    u.get("produces"),
                    u["id"],
                )
            )
    out = [header("port/inventory.json")]
    out.append("use super::Route;\n\n")
    out.append("/// Every upstream JAX-RS resource method under `/Engine.svc`.\n")
    out.append(f"pub const ROUTES: [Route; {len(rows)}] = [\n")
    for verb, cls, full, secured, launcher, produces, unit in rows:
        prod = f"Some({json.dumps(produces)})" if produces else "None"
        out.append(
            f"    Route {{ method: {json.dumps(verb)}, class: {json.dumps(cls)}, path: {json.dumps(full)}, "
            f"secured: {str(secured).lower()}, launcher_checks: {str(launcher).lower()}, produces: {prod}, "
            f"unit: {json.dumps(unit)} }},\n"
        )
    out.append("];\n")
    path = ROOT / "crates/sbrw-http/src/engine/routes.rs"
    path.parent.mkdir(parents=True, exist_ok=True)
    write_rust(path, "".join(out))
    print(f"wrote {path.relative_to(ROOT)} ({len(rows)} routes)")


PRIMITIVES = {"int": "i32", "long": "i64", "short": "i16", "byte": "i8", "boolean": "bool", "float": "f32", "double": "f64"}
SIMPLE = {
    "java.lang.Integer": "i32",
    "java.lang.Long": "i64",
    "java.lang.Short": "i16",
    "java.lang.Byte": "i8",
    "java.lang.Boolean": "bool",
    "java.lang.Float": "f32",
    "java.lang.Double": "f64",
    "java.lang.String": "String",
    "javax.xml.datatype.XMLGregorianCalendar": "crate::DateTime",
    **PRIMITIVES,
}
RUST_KEYWORDS = {
    "as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let",
    "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type",
    "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
}


def snake(name: str) -> str:
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s).lower()
    if s in ("self", "super", "crate"):
        return s + "_"
    return "r#" + s if s in RUST_KEYWORDS else s


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def dtos() -> None:
    """Rust for upstream's JAXB classes, from the JVM's model of them (fixtures/dto/schema.json)."""
    schema = json.loads((ROOT / "fixtures/dto/schema.json").read_text())
    classes = {c["java"]: c for c in schema["classes"]}
    enums = {e["java"]: e for e in schema["enums"]}
    def pkg(java):
        """Module for a Java package: com.soapboxrace.jaxb.<p> -> <p>; core.engine -> engine;
        core.xmpp (Openfire's REST responses) -> openfire."""
        parts = java.split(".")
        return parts[3] if parts[2] == "jaxb" else {"engine": "engine", "xmpp": "openfire"}[parts[3]]

    packages = sorted({pkg(j) for j in list(classes) + list(enums)})

    def name(java):
        return java.split(".")[-1].replace("$", "")

    def path(java, here):
        return name(java) if pkg(java) == here else f"super::{pkg(java)}::{name(java)}"

    def props(c):
        """Base-class properties first, as JAXB marshals them."""
        base = classes[c["base"]] if c["base"] else None
        return (props(base) if base else []) + c["properties"]

    # Classes that reach themselves through optional (non-list) properties need Box.
    def optional_beans(c):
        for p in props(c):
            if p["kind"] == "element" and not p["collection"] and p["types"][0]["type"] in classes:
                yield p["types"][0]["type"]

    def reaches(start, target, seen=()):
        for nxt in optional_beans(classes[start]):
            if nxt == target or (nxt not in seen and reaches(nxt, target, seen + (nxt,))):
                return True
        return False

    boxed = {j for j in classes if reaches(j, j)}

    def field(p, here):
        """(field name, Rust type, shape, item kind, XML name, Java target type)."""
        java_type = p["java_type"]
        if p["kind"] == "attribute":
            target, xml = p["type"], p["xml"]
        else:
            target, xml = p["types"][0]["type"], p["types"][0]["xml"]
        if target in SIMPLE:
            item, item_kind = SIMPLE[target], "value"
        elif target in enums:
            item, item_kind = path(target, here), "value"
        elif target in classes:
            item, item_kind = path(target, here), "bean"
            if target in boxed and not p["collection"]:
                item = f"Box<{item}>"
        else:
            raise ValueError(f"unmapped type {target}")
        if p["collection"]:
            shape = "wrapped" if p.get("wrapper") else "list"
            rust = f"Option<Vec<{item}>>" if shape == "wrapped" else f"Vec<{item}>"
        elif java_type in PRIMITIVES:
            shape, rust = "required", PRIMITIVES[java_type]
        else:
            shape, rust = "optional", f"Option<{item}>"
        return snake(p["name"]), rust, shape, item_kind, xml, target

    def default(p, rust, shape, target, here):
        d = p["default"]
        if shape == "list":
            return "Vec::new()"
        if shape == "wrapped":
            return "Some(Vec::new())" if d == [] else "None"
        if shape == "required":
            if d is None:
                d = False if rust == "bool" else 0
            if rust == "bool":
                return "true" if d else "false"
            if rust in ("f32", "f64"):
                return f"{float(d)!r}{rust}"
            return f"{int(d)}{rust}"
        if d is None:
            return "None"
        if isinstance(d, dict):
            return "Some(Default::default())"
        if target in enums:
            return f"Some({path(target, here)}::{d})"
        if isinstance(d, bool):
            return f"Some({'true' if d else 'false'})"
        if isinstance(d, str):
            return f"Some({rust_str(d)}.into())"
        inner = rust[len("Option<") : -1]
        return f"Some({float(d)!r}{inner})" if inner in ("f32", "f64") else f"Some({int(d)}{inner})"

    out_dir = ROOT / "crates/sbrw-xml/src/dto"
    out_dir.mkdir(parents=True, exist_ok=True)
    gen_header = header("fixtures/dto/schema.json (JAXB's runtime model of com.soapboxrace.jaxb.*)")
    registry = []
    for here in packages:
        out = [gen_header]
        out.append("#![allow(non_camel_case_types, clippy::derivable_impls, clippy::single_match)]\n\n")
        out.append("use crate::{Element, XmlType, XmlValue, XmlWriter};\n\n")
        for java, e in sorted(enums.items()):
            if pkg(java) != here:
                continue
            n = name(java)
            out.append(f"/// `{java}`\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub enum {n} {{\n")
            out += [f"    {k['name']},\n" for k in e["constants"]]
            out.append(f"}}\n\nimpl XmlValue for {n} {{\n    fn print(&self) -> String {{\n        match self {{\n")
            out += [f"            Self::{k['name']} => {rust_str(k['xml'])},\n" for k in e["constants"]]
            out.append("        }\n        .into()\n    }\n\n    fn parse(text: &str) -> Option<Self> {\n")
            out.append("        match text.trim_matches([' ', '\\t', '\\n', '\\r']) {\n")
            out += [f"            {rust_str(k['xml'])} => Some(Self::{k['name']}),\n" for k in e["constants"]]
            out.append("            _ => None,\n        }\n    }\n}\n\n")
        for java, c in sorted(classes.items()):
            if pkg(java) != here:
                continue
            n = name(java)
            fields = [(p, *field(p, here)) for p in props(c)]
            names = [f[1] for f in fields]
            assert len(names) == len(set(names)), f"{java}: duplicate field names {names}"
            xml_names = [f[5] for f in fields if f[0]["kind"] == "element"]
            assert len(xml_names) == len(set(xml_names)), f"{java}: duplicate element names {xml_names}"
            out.append(f"/// `{java}`, written as `<{c['root']}>`.\n#[derive(Debug, Clone, PartialEq)]\npub struct {n} {{\n")
            out += [f"    pub {fname}: {rust},\n" for _, fname, rust, *_ in fields]
            out.append(f"}}\n\nimpl Default for {n} {{\n    fn default() -> Self {{\n        Self {{\n")
            out += [
                f"            {fname}: {default(p, rust, shape, target, here)},\n"
                for p, fname, rust, shape, _kind, _xml, target in fields
            ]
            out.append("        }\n    }\n}\n\n")

            attrs = [f for f in fields if f[0]["kind"] == "attribute"]
            elems = [f for f in fields if f[0]["kind"] == "element"]
            out.append(f"impl XmlType for {n} {{\n")
            if attrs:
                out.append("    fn write_attributes(&self, w: &mut XmlWriter) {\n")
                for p, fname, rust, shape, kind, xml, target in attrs:
                    if shape == "required":
                        out.append(f"        w.attribute({rust_str(xml)}, &self.{fname}.print());\n")
                    else:
                        out.append(f"        if let Some(v) = &self.{fname} {{\n            w.attribute({rust_str(xml)}, &v.print());\n        }}\n")
                out.append("    }\n\n")
            out.append(f"    fn write_children(&self, {'w' if elems else '_w'}: &mut XmlWriter) {{\n")
            for p, fname, rust, shape, kind, xml, target in elems:
                call = "value" if kind == "value" else "bean"
                if shape == "required":
                    out.append(f"        w.{call}({rust_str(xml)}, &self.{fname});\n")
                elif shape == "optional":
                    out.append(f"        if let Some(v) = &self.{fname} {{\n            w.{call}({rust_str(xml)}, v);\n        }}\n")
                elif shape == "list":
                    out.append(f"        for v in &self.{fname} {{\n            w.{call}({rust_str(xml)}, v);\n        }}\n")
                else:
                    wrapper = p["wrapper"]
                    out.append(
                        f"        if let Some(list) = &self.{fname} {{\n            w.open({rust_str(wrapper)});\n"
                        f"            for v in list {{\n                w.{call}({rust_str(xml)}, v);\n            }}\n"
                        "            w.close();\n        }\n"
                    )
            out.append("    }\n\n")
            uses_e = bool(attrs or elems)
            out.append(f"    fn read_from(&mut self, {'e' if uses_e else '_e'}: &Element) {{\n")
            if attrs:
                out.append("        for (name, text) in &e.attributes {\n            match name.as_str() {\n")
                for p, fname, rust, shape, kind, xml, target in attrs:
                    target_set = f"self.{fname} = v" if shape == "required" else f"self.{fname} = Some(v)"
                    out.append(
                        f"                {rust_str(xml)} => {{\n                    if let Some(v) = XmlValue::parse(text) {{\n"
                        f"                        {target_set};\n                    }}\n                }}\n"
                    )
                out.append("                _ => {}\n            }\n        }\n")
            if elems:
                out.append("        for c in &e.children {\n            match c.name.as_str() {\n")
                for p, fname, rust, shape, kind, xml, target in elems:
                    key = rust_str(p["wrapper"] if shape == "wrapped" else xml)
                    item_type = path(target, here) if kind == "bean" else None
                    if kind == "value":
                        read = "XmlValue::parse(c.text())"
                        if shape == "required":
                            body = f"if let Some(v) = {read} {{\n                        self.{fname} = v;\n                    }}"
                        elif shape == "optional":
                            body = f"if let Some(v) = {read} {{\n                        self.{fname} = Some(v);\n                    }}"
                        elif shape == "list":
                            body = f"if let Some(v) = {read} {{\n                        self.{fname}.push(v);\n                    }}"
                        else:
                            body = f"self.{fname} = Some(c.children_named({rust_str(xml)}).filter_map(|i| XmlValue::parse(i.text())).collect());"
                    elif shape == "optional":
                        value = f"Box::new({item_type}::read(c))" if target in boxed else f"{item_type}::read(c)"
                        body = f"self.{fname} = Some({value});"
                    elif shape == "list":
                        body = f"self.{fname}.push({item_type}::read(c));"
                    else:
                        body = f"self.{fname} = Some(c.children_named({rust_str(xml)}).map({item_type}::read).collect());"
                    out.append(f"                {key} => {{\n                    {body}\n                }}\n")
                out.append("                _ => {}\n            }\n        }\n")
            out.append("    }\n}\n\n")
            out.append(f"impl crate::XmlRoot for {n} {{\n    const ROOT: &'static str = {rust_str(c['root'])};\n}}\n\n")
            if not c["abstract"]:
                registry.append((java, f"{here}::{n}"))
        write_rust(out_dir / f"{here}.rs", "".join(out).rstrip() + "\n")

    mod = [gen_header.replace("// ", "//! ", 1)]
    mod.append("//! Upstream's XML classes: one module per `com.soapboxrace.jaxb` package, plus `engine`\n//! (error responses) and `openfire` (Openfire REST responses).\n\n")
    mod += [f"pub mod {p};\n" for p in packages]
    mod.append("\n#[cfg(test)]\nmod tests;\n\n")
    mod.append("/// A class by Java name: parse-then-write, and its default written.\n")
    mod.append("#[cfg(test)]\npub(crate) type Entry = (&'static str, fn(&str) -> Result<String, crate::XmlError>, fn() -> String);\n\n")
    mod.append("/// Every concrete class.\n#[cfg(test)]\npub(crate) const REGISTRY: &[Entry] = &[\n")
    for java, rust in registry:
        mod.append(
            f"    ({rust_str(java)}, |xml| crate::from_xml::<{rust}>(xml).map(|v| crate::ToXml::to_xml(&v)), "
            f"|| crate::ToXml::to_xml(&{rust}::default())),\n"
        )
    mod.append("];\n")
    write_rust(out_dir / "mod.rs", "".join(mod))
    print(f"wrote crates/sbrw-xml/src/dto/ ({len(classes)} classes, {len(enums)} enums, {len(boxed)} boxed)")


